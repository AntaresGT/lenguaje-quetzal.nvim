local pruebas = require("tests.auxiliar")
local configuracion = require("quetzal.configuracion")

pruebas.prueba("los valores predeterminados usan el servidor oficial", function()
  local opciones = configuracion.valores_predeterminados()
  pruebas.igual({ "quetzal-lsp", "--stdio" }, opciones.lsp.comando)
  pruebas.igual(true, opciones.lsp.habilitado)
  pruebas.igual(false, opciones.asignaciones.habilitadas)
  pruebas.igual(true, opciones.arbol_sintaxis.habilitado)
  pruebas.igual(false, opciones.arbol_sintaxis.plegado)
end)

pruebas.prueba("la combinación conserva valores y reemplaza el comando completo", function()
  local opciones = configuracion.combinar({
    lsp = { comando = { "C:\\Quetzal\\quetzal-lsp.exe", "--stdio" } },
    arbol_sintaxis = { plegado = true },
    asignaciones = { hover = false },
  })
  pruebas.igual({ "C:\\Quetzal\\quetzal-lsp.exe", "--stdio" }, opciones.lsp.comando)
  pruebas.igual(true, opciones.lsp.habilitado)
  pruebas.igual(true, opciones.arbol_sintaxis.plegado)
  pruebas.igual(false, opciones.asignaciones.hover)
  pruebas.igual("gd", opciones.asignaciones.definicion)
end)

pruebas.prueba("la validación rechaza tipos y opciones desconocidas", function()
  pruebas.falla_con("setup", function()
    configuracion.combinar("incorrecto")
  end)
  pruebas.falla_con("lsp.habilitado", function()
    configuracion.combinar({ lsp = { habilitado = "sí" } })
  end)
  pruebas.falla_con("opción reconocida", function()
    configuracion.combinar({ inventada = true })
  end)
  pruebas.falla_con("lsp.comando[2]", function()
    configuracion.combinar({ lsp = { comando = { "quetzal-lsp", 3 } } })
  end)
  pruebas.falla_con("lista sin claves adicionales", function()
    configuracion.combinar({ lsp = { comando = { "quetzal-lsp", extra = "--stdio" } } })
  end)
end)

pruebas.prueba("la configuración nativa no puede romper el contrato del comando o filetype", function()
  pruebas.falla_con("lsp.configuracion.cmd", function()
    configuracion.combinar({ lsp = { configuracion = { cmd = { "otro" } } } })
  end)
  pruebas.falla_con("lsp.configuracion.filetypes", function()
    configuracion.combinar({ lsp = { configuracion = { filetypes = { "lua" } } } })
  end)
end)
